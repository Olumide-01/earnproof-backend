import {
  HorizonHttpDateTimeSource,
  HorizonLedgerTimeSource,
  parseHttpDate,
  parseLatestLedgerTime,
  TimeSourceError,
} from "./ledger-time-source";

function response(options: {
  ok?: boolean;
  status?: number;
  body?: unknown;
  date?: string | null;
}) {
  return {
    ok: options.ok ?? true,
    status: options.status ?? 200,
    headers: { get: (name: string) => (name === "date" ? (options.date ?? null) : null) },
    json: async () => options.body,
  };
}

const ledgerBody = {
  _embedded: {
    records: [{ sequence: 123_456, closed_at: "2030-01-01T00:00:05Z" }],
  },
};

describe("parseLatestLedgerTime", () => {
  it("reads the newest ledger's close time, sequence and stated uncertainty", () => {
    expect(parseLatestLedgerTime(ledgerBody, 10_000)).toEqual({
      referenceMs: Date.parse("2030-01-01T00:00:05Z"),
      resolutionMs: 1_000,
      maxReferenceLagMs: 10_000,
      sequence: 123_456,
    });
  });

  it("accepts a sequence encoded as a string", () => {
    const body = { _embedded: { records: [{ sequence: "42", closed_at: "2030-01-01T00:00:05Z" }] } };
    expect(parseLatestLedgerTime(body, 0).sequence).toBe(42);
  });

  it.each([
    ["no records", { _embedded: { records: [] } }],
    ["not an object", null],
    ["zone-less timestamp", { _embedded: { records: [{ sequence: 1, closed_at: "2030-01-01T00:00:05" }] } }],
    ["offset timestamp", { _embedded: { records: [{ sequence: 1, closed_at: "2030-01-01T00:00:05+01:00" }] } }],
    ["non-positive sequence", { _embedded: { records: [{ sequence: 0, closed_at: "2030-01-01T00:00:05Z" }] } }],
  ])("rejects a malformed body: %s", (_label, body) => {
    expect(() => parseLatestLedgerTime(body, 0)).toThrow(TimeSourceError);
  });
});

describe("parseHttpDate", () => {
  it("parses an IMF-fixdate with one-second resolution and no lag", () => {
    expect(parseHttpDate("Tue, 01 Jan 2030 00:00:00 GMT")).toEqual({
      referenceMs: Date.parse("2030-01-01T00:00:00Z"),
      resolutionMs: 1_000,
      maxReferenceLagMs: 0,
    });
  });

  it("refuses an absent header", () => {
    expect(() => parseHttpDate(null)).toThrow(new TimeSourceError("date_header_absent"));
  });

  it.each(["Tuesday, 01-Jan-30 00:00:00 GMT", "Tue Jan  1 00:00:00 2030", "garbage"])(
    "refuses an obsolete or ambiguous format: %s",
    (value) => {
      expect(() => parseHttpDate(value)).toThrow(new TimeSourceError("date_header_malformed"));
    },
  );
});

describe("HorizonLedgerTimeSource", () => {
  it("requests the newest ledger only", async () => {
    const fetchImpl = jest.fn().mockResolvedValue(response({ body: ledgerBody }));
    const source = new HorizonLedgerTimeSource("https://horizon.example/", 10_000, fetchImpl);

    await source.read(new AbortController().signal);

    expect(fetchImpl).toHaveBeenCalledWith(
      "https://horizon.example/ledgers?order=desc&limit=1",
      expect.objectContaining({ method: "GET" }),
    );
  });

  it("reports only the upstream status code on failure, never the body", async () => {
    const fetchImpl = jest
      .fn()
      .mockResolvedValue(response({ ok: false, status: 503, body: { detail: "internal host db-1" } }));
    const source = new HorizonLedgerTimeSource("https://horizon.example", 10_000, fetchImpl);

    await expect(source.read(new AbortController().signal)).rejects.toThrow(
      new TimeSourceError("upstream_status_503"),
    );
  });
});

describe("HorizonHttpDateTimeSource", () => {
  it("reads the Date header even when the status is not 2xx", async () => {
    // The header is generated by the server regardless of the route's status.
    const fetchImpl = jest
      .fn()
      .mockResolvedValue(response({ ok: false, status: 404, date: "Tue, 01 Jan 2030 00:00:00 GMT" }));
    const source = new HorizonHttpDateTimeSource("https://horizon.example", fetchImpl);

    await expect(source.read(new AbortController().signal)).resolves.toMatchObject({
      referenceMs: Date.parse("2030-01-01T00:00:00Z"),
    });
  });
});
